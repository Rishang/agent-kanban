// Ticket files. With the project setting ticketStorage = "files" every open ticket is also written to
// TicketDir/<id>.yml (see ticketexport.go). The file is a read-only export: the board database stays the
// source of truth, and a hand edit is overwritten on the ticket's next change.

// TicketStorageFiles is the ticketStorage setting that exports tickets as YAML files in the repo.
const TicketStorageFiles = "files"

// TicketDir is the repo folder for ticket files.
const TicketDir = ".agent-kanban/tasks"

// ticketHeader is the first line of every generated file; the export only ever removes files that start with it.
const ticketHeader = "# generated by agent-kanban: change this ticket through MCP or the board; edits here are overwritten"

// TicketFile is the content of one ticket file, in file order.
type TicketFile struct {
	ID          string          `yaml:"id"`
	Title       string          `yaml:"title"`
	Status      string          `yaml:"status"` // open, done or closed: the column's role
	Column      string          `yaml:"column"` // the column's name
	Priority    string          `yaml:"priority"`
	Assignee    string          `yaml:"assignee"`
	Labels      []string        `yaml:"labels"`
	Parent      string          `yaml:"parent"`
	Due         string          `yaml:"due"`
	Human       bool            `yaml:"human"`
	Created     string          `yaml:"created"`
	Subtasks    []TicketSubtask `yaml:"subtasks,omitempty"`
	Plan        *TicketPlan     `yaml:"plan,omitempty"`
	Description string          `yaml:"description"`
	Checklist   []TicketCheck   `yaml:"checklist,omitempty"`
	Comments    []TicketComment `yaml:"comments,omitempty"`
}

type TicketSubtask struct {
	ID     string `yaml:"id"`
	Title  string `yaml:"title"`
	Status string `yaml:"status"`
}

type TicketPlan struct {
	Status  string `yaml:"status"`
	Version int    `yaml:"version"`
}

type TicketCheck struct {
	Text string `yaml:"text"`
	Done bool   `yaml:"done"`
}

type TicketComment struct {
	Who  string `yaml:"who"`
	At   string `yaml:"at"`
	Text string `yaml:"text"`
}

// Ticket statuses in a file: the role of the ticket's column.
const (
	TicketOpen   = "open"
	TicketDone   = RoleDone
	TicketClosed = RoleClosed
)

func ticketStatus(col string, cols []Column) string {
	if c, ok := ClosedColumn(cols); ok && c.ID == col {
		return TicketClosed
	}
	if Finished(cols)[col] {
		return TicketDone
	}
	return TicketOpen
}

func fileTime(ms int64) string { return time.UnixMilli(ms).UTC().Format(time.RFC3339) }

var trailingWS = regexp.MustCompile(`[ \t]+\n`)

// fileText trims trailing spaces per line: a line ending in a space can't be a YAML literal block, and the
// board renders the text the same without them.
func fileText(s string) string {
	if !strings.Contains(s, "\n") {
		return s
	}
	return strings.TrimRight(trailingWS.ReplaceAllString(s, "\n"), " \t")
}

// ticketFileOf builds the file content of t; subs are its sub-tasks (any column), cols the board's columns.
func ticketFileOf(t Task, cols []Column, subs []Task) TicketFile {
	f := TicketFile{
		ID: t.ID, Title: t.Title, Status: ticketStatus(t.Column, cols), Column: t.Column, Priority: t.Priority,
		Assignee: t.Assignee, Labels: slices.Sorted(slices.Values(t.Labels)), Parent: t.Parent, Due: t.Due,
		Human: t.Human, Created: fileTime(t.Created), Description: fileText(t.Description),
	}
	if f.Labels == nil {
		f.Labels = []string{}
	}
	for _, c := range cols {
		if c.ID == t.Column {
			f.Column = c.Name
		}
	}
	for _, s := range subs {
		f.Subtasks = append(f.Subtasks, TicketSubtask{s.ID, s.Title, ticketStatus(s.Column, cols)})
	}
	if t.PlanStatus != "" {
		f.Plan = &TicketPlan{t.PlanStatus, t.PlanVersion}
	}
	for _, c := range t.Checklist {
		f.Checklist = append(f.Checklist, TicketCheck{fileText(c.Text), c.Done})
	}
	for _, c := range t.Comments {
		f.Comments = append(f.Comments, TicketComment{c.Who, fileTime(c.T), fileText(c.Text)})
	}
	return f
}

// RenderTicket writes f as YAML: fixed key order, labels on one line, multi-line text as literal | blocks.
// The same content always gives the same bytes, so two machines exporting a ticket don't conflict.
func RenderTicket(f TicketFile) ([]byte, error) {
	var doc yaml.Node
	if err := doc.Encode(f); err != nil {
		return nil, err
	}
	var style func(n *yaml.Node)
	style = func(n *yaml.Node) {
		if n.Kind == yaml.ScalarNode && n.Tag == "!!str" && strings.Contains(n.Value, "\n") {
			n.Style = yaml.LiteralStyle
		}
		for i, c := range n.Content {
			if n.Kind == yaml.MappingNode && i%2 == 1 && n.Content[i-1].Value == "labels" {
				c.Style = yaml.FlowStyle
			}
			style(c)
		}
	}
	style(&doc)
	var b bytes.Buffer
	b.WriteString(ticketHeader + "\n")
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(&doc); err != nil {
		return nil, err
	}
	enc.Close()
	return b.Bytes(), nil
}

// ParseTicket reads a ticket file (phase 2 imports and tests use it).
func ParseTicket(src []byte) (TicketFile, error) {
	var f TicketFile
	err := yaml.Unmarshal(src, &f)
	return f, err
}
